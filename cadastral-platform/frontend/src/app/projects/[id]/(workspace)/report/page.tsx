"use client";
import { api } from "@/lib/api";
import { useRemote } from "@/lib/useRemote";
import { ArtifactList, PageThumb } from "@/components/ArtifactList";
import { SampleBanner } from "@/components/ui/Status";

export default function Report({ params }: { params: { id: string } }) {
  const { data, sample, error, loading } = useRemote(() => api.artifacts(params.id), [params.id]);
  const docs = data?.filter((a) => a.kind === "site_report_pdf" || a.kind === "constraints_report_pdf") ?? [], main = docs[0];
  return (
    <div>
      {sample && <SampleBanner what="The report" />}
      <p className="h-eyebrow">Site report</p>
      <h2 className="mt-2 font-display text-3xl font-medium">The report, as a document</h2>
      <p className="mt-3 max-w-3xl text-sm leading-relaxed text-muted">The A4 report covers the cover and summary, zoning, constraints, cited requirements and the civil page, with an appendix. It is an indicative draft for a qualified person to check.</p>
      {error && <p role="alert" className="mt-4 text-danger">{error}</p>}
      {loading && !data && <p className="mt-6 text-muted">Loading...</p>}
      {data && (docs.length ? <div className="mt-6"><ArtifactList items={docs} projectId={params.id} /></div> : <p className="mt-6 border border-ink/30 hatch p-4 text-sm">The report has not been produced yet. It is generated by the run.</p>)}
      {main && <><h3 className="mt-12 font-mono text-[11px] uppercase tracking-[.2em] text-gold">Pages</h3>
        <div className="mt-4 grid grid-cols-2 gap-5 sm:grid-cols-3 lg:grid-cols-5">{Array.from({ length: Math.min(main.pages ?? 5, 10) }, (_, i) => <PageThumb key={i} artifactId={main.id} n={i + 1} label={`Page ${i + 1}`} />)}</div></>}
    </div>
  );
}
