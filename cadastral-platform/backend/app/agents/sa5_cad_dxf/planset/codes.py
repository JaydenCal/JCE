VIEWPORT_LAYER = "JCS-VIEW-VPRT-NONE"
_BY_OLD: dict[str, tuple[str, str]] = {o: k for k, v in ELEMENTS.items() for o in v[4] if not o.endswith("*")}
_PREFIX_OLD = {o[:-1]: k for k, v in ELEMENTS.items() for o in v[4] if o.endswith("*")}


def _type(kind: str, element_key, pattern_or_hatch: bool) -> str:
    if kind == "text":
        return "TEXT"
    if kind == "fill":
        return "HATCH"
    return "LINE"


def jcs_layer(old: str, kind: str, hatched: bool = False) -> str:
    """JCS layer name for a ref-style layer name and item kind (line | fill | text | image)."""
    key = _BY_OLD.get(old) or next((k for p, k in _PREFIX_OLD.items() if old.startswith(p)), None)
    if old.startswith("JCS-"):
        return old
    if key is None:
        key = ("ANNO", "NOTE")
    return f"JCS-{key[0]}-{key[1]}-{_type(kind, key, hatched)}"


def all_jcs_layers() -> list[LayerDef]:
    out: list[LayerDef] = []
    for (disc, el), (aci, lw, lt, desc, _o) in ELEMENTS.items():
        if (disc, el) == ("VIEW", "VPRT"):
            out.append(LayerDef(VIEWPORT_LAYER, aci, lt, lw, desc, extra=True))
            continue
        for t in ("LINE", "HATCH", "TEXT"):
            out.append(LayerDef(f"JCS-{disc}-{el}-{t}", aci, lt, lw, f"{desc} ({t.lower()})", extra=True))
    return out


def apply_layer_scheme(pages) -> int:
    """Rename the layer of every item on ref-style pages ([(sheet, [views])]) to the JCS scheme; returns the number of items changed.
    Called only by the ref-style build, so legacy sheets are never touched."""
    n = 0
    for _sh, views in pages:
        for v in views:
            for it in v.items:
                new = jcs_layer(it.layer, it.kind, bool(it.pattern or it.hatch))
                if new != it.layer:
                    it.layer = new
                    n += 1
    return n


def layer_legend_markdown() -> str:
    rows = ["| Layer name | Colour (ACI) | Lineweight (mm) | Linetype | Description | Replaces (ref-style working name) |", "|---|---|---|---|---|---|"]
    for l in all_jcs_layers():
        key = next(k for k in ELEMENTS if l.name.startswith(f"JCS-{k[0]}-{k[1]}-"))
        old = ", ".join(f"`{o}`" for o in ELEMENTS[key][4]) or "new"
        rows.append(f"| `{l.name}` | {l.aci} | {l.lineweight_mm:.2f} | {l.linetype} | {l.description} | {old} |")
    return "\n".join(rows)


def sheet_table_markdown() -> str:
    rows = ["| Sheet | NNN | Title | Drawing number (job empty) | Drawing number (job 004) |", "|---|---|---|---|---|"]
    for s, n in SHEET_NNN.items():
        rows.append(f"| {s} | {n} | {SHEET_TITLES[s]} | `{drawing_number(s)}` | `{drawing_number(s, '004')}` |")
    return "\n".join(rows)
