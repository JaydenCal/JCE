// Builds golive/wrangler.live.toml from pocket-architect-source/wrangler.toml (the live Worker identity plus the release vars),
// changing only the two paths so the config can sit in golive/ (the launch package has no pocket-architect-source/wrangler.toml).
//   node golive/build-live-config.mjs           writes golive/wrangler.live.toml
//   node golive/build-live-config.mjs --check   exits 1 if the committed file is stale or unsafe (also checks the rules below)
// Rules checked on the comment-stripped lines: Worker name, D1 id, route, no STAGING or staging names, no secret name under [vars],
// PLAN_PACK_PRICE_CENTS = "3000", PORTAL_ENABLED = "1".
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const srcPath = join(here, '..', 'pocket-architect-source', 'wrangler.toml');
const outPath = join(here, 'wrangler.live.toml');
const SECRETS = ['STRIPE_SECRET_KEY', 'STRIPE_WEBHOOK_SECRET', 'STRIPE_PRICE_ID', 'RESEND_API_KEY', 'ADMIN_TOKEN', 'ENTITLEMENT_SECRET', 'IP_HASH_SALT', 'ANTHROPIC_API_KEY', 'TEST_CODES'];

export function build(src) {
  let out = src.replace(/\r\n/g, '\n');
  const must = (re, label) => { if (!re.test(out)) throw new Error(`source wrangler.toml has no ${label} line`); };
  must(/^main = "server\/worker\.js"/m, 'main');
  must(/^migrations_dir = "server\/migrations"/m, 'migrations_dir');
  out = out.replace(/^main = "server\/worker\.js"/m, 'main = "../pocket-architect-source/server/worker.js"');
  out = out.replace(/^migrations_dir = "server\/migrations"/m, 'migrations_dir = "../pocket-architect-source/server/migrations"');
  const head = '# GENERATED by golive/build-live-config.mjs from pocket-architect-source/wrangler.toml. Do not edit by hand: change the source and rebuild.\n# Only main and migrations_dir differ (paths relative to this folder). Used by golive/deploy-live.ps1 (LIVE Worker pocket-architect-api).\n\n';
  return head + out;
}

export function problems(text) {
  const lines = text.split('\n').map((l) => l.replace(/#.*$/, '').trim()).filter(Boolean);
  const bad = [];
  if (!lines.includes('name = "pocket-architect-api"')) bad.push('Worker name is not pocket-architect-api');
  if (!lines.some((l) => /^routes\s*=.*glideinside\.com\.au\/api\/\*/.test(l))) bad.push('route glideinside.com.au/api/* is missing');
  if (!lines.includes('database_id = "fccdf1f7-e48c-4c72-8723-b343b3f2fad4"')) bad.push('live D1 id is missing');
  if (!lines.includes('database_name = "pocket-architect"')) bad.push('D1 database_name is not pocket-architect');
  if (!lines.includes('bucket_name = "pocket-architect-files"')) bad.push('R2 bucket is not pocket-architect-files');
  if (lines.some((l) => /staging/i.test(l))) bad.push('a staging name or STAGING variable is present');
  if (lines.some((l) => /^STAGING\s*=/.test(l))) bad.push('STAGING variable present');
  if (!lines.includes('PLAN_PACK_PRICE_CENTS = "3000"')) bad.push('PLAN_PACK_PRICE_CENTS is not "3000"');
  if (!lines.includes('PORTAL_ENABLED = "1"')) bad.push('PORTAL_ENABLED is not "1"');
  for (const s of SECRETS) if (lines.some((l) => new RegExp(`^${s}\\s*=`).test(l))) bad.push(`secret ${s} is set under [vars]`);
  if (lines.some((l) => /^REPLACE-WITH|PASTE_ID/.test(l))) bad.push('placeholder left in file');
  return bad;
}

if (process.argv[1] && join(process.argv[1]) === fileURLToPath(import.meta.url)) {
  if (!existsSync(srcPath)) { console.error(`Missing ${srcPath}`); process.exit(2); }
  const built = build(readFileSync(srcPath, 'utf8'));
  const p = problems(built);
  if (p.length) { console.error('Unsafe live config:\n - ' + p.join('\n - ')); process.exit(1); }
  if (process.argv.includes('--check')) {
    const have = existsSync(outPath) ? readFileSync(outPath, 'utf8').replace(/\r\n/g, '\n') : '';
    if (have !== built) { console.error('golive/wrangler.live.toml is stale. Run: node golive/build-live-config.mjs'); process.exit(1); }
    console.log('wrangler.live.toml is current and passes the live checks.');
  } else {
    writeFileSync(outPath, built);
    console.log('Wrote golive/wrangler.live.toml');
  }
}
