// End to end run of the residential guided flow with screenshots and assertions (exit 1 on a failed check).
//   node tools/resiflow-shots.cjs [outDir]        Playwright: PLAYWRIGHT_PATH or a local install
const path = require('path'); const fs = require('fs');
const { chromium } = require(process.env.PLAYWRIGHT_PATH || 'playwright');
const { startServer, newPage, ADDRESS } = require('./resiflow-harness.cjs');
const OUT = path.resolve(process.argv[2] || '/home/claude/resiflow-shots');
const fails = []; const log = [];
const check = (ok, msg) => { console.log(`${ok ? 'ok  ' : 'FAIL'} ${msg}`); if (!ok) fails.push(msg); };
(async () => {
  fs.mkdirSync(OUT, { recursive: true });
  const { ORIGIN, close } = await startServer();
  const browser = await chromium.launch({ args: ['--use-gl=swiftshader', '--enable-webgl', '--ignore-gpu-blocklist'] });
  const T = 120000;
  for (const [w, hgt, tag] of [[1440, 900, '1440'], [390, 844, '390']]) {
    const page = await newPage(browser, { width: w, height: hgt }, log);
    page.setDefaultTimeout(T);
    const shot = async (n) => { await page.waitForTimeout(900); await page.screenshot({ path: path.join(OUT, `res-${n}-${tag}.png`), timeout: T }); console.log('shot', n, tag); };
    const stepNo = () => page.evaluate(() => Number(document.querySelector('[data-ps="flow-root"]')?.dataset.step || 0));
    const next = async () => { await page.click('[data-ps="flow-next"]'); await page.waitForTimeout(400); };
    await page.goto(`${ORIGIN}/plan-studio/app/`, { waitUntil: 'domcontentloaded' });
    await page.waitForSelector('[data-ps="flow-root"]:not([hidden])');
    check(await stepNo() === 1, `${tag}: a fresh open starts the flow at step 1`);
    check(await page.evaluate(() => document.querySelector('[data-ps="flow-next"]').disabled), `${tag}: Next is disabled until a lot is found`);
    check((await page.locator('[data-ps="flow-progress"] li').count()) === 5, `${tag}: five steps in the progress indicator`);
    await shot('1a-find');
    await page.fill('[data-ps="flow-address"]', '14 Sample');
    await page.waitForSelector('[data-ps="flow-suggest"] li');
    await shot('1b-suggest');
    await page.click('[data-ps="flow-suggest"] li');
    await page.waitForSelector('[data-ps="flow-lot-label"]');
    await page.waitForTimeout(2500);
    check(/Lot 7/.test(await page.textContent('[data-ps="flow-lot-label"]')), `${tag}: the lot is confirmed`);
    await shot('1c-lot-confirm');
    await next();
    check(await stepNo() === 2, `${tag}: Next goes to step 2`);
    await page.waitForSelector('[data-ps="flow-home"]');
    check((await page.locator('[data-ps="flow-home"]').count()) >= 2, `${tag}: homes are listed`);
    await shot('2a-choose');
    await page.selectOption('[data-ps="flow-filter-bedrooms"]', '3');
    const n3 = await page.locator('[data-ps="flow-home"]').count();
    await shot('2b-filter-3bed');
    await page.selectOption('[data-ps="flow-filter-bedrooms"]', '');
    check(n3 <= (await page.locator('[data-ps="flow-home"]').count()), `${tag}: the bedroom filter narrows the list`);
    check(await page.evaluate(() => document.querySelector('[data-ps="flow-next"]').disabled), `${tag}: Next is disabled until a home is chosen`);
    await page.locator('[data-ps="flow-home"]').first().click();
    await next();
    check(await stepNo() === 3, `${tag}: Next goes to step 3`);
    await page.waitForSelector('[data-ps="flow-house"]');
    await page.waitForFunction(() => !document.querySelector('[data-ps="flow-placing"]'));
    await page.waitForTimeout(600);
    const st0 = await page.evaluate(() => document.querySelector('[data-ps="flow-place-status"]').dataset.state);
    check(['inside', 'unknown'].includes(st0), `${tag}: the home is auto placed (status ${st0})`);
    await shot('3a-place');
    const pos0 = await page.evaluate(() => JSON.stringify(window.__ps.store.project.levels[0].rooms[0].polygon[0]));
    await page.click('[data-ps="flow-nudge-right"]');
    await page.click('[data-ps="flow-nudge-down"]');
    const pos1 = await page.evaluate(() => JSON.stringify(window.__ps.store.project.levels[0].rooms[0].polygon[0]));
    check(pos0 !== pos1, `${tag}: nudge moves the home`);
    await page.click('[data-ps="flow-rot-right"]');
    await page.click('[data-ps="flow-mirror"]');
    await shot('3b-rotated-mirrored');
    await page.click('[data-ps="flow-bestfit"]');
    await page.waitForFunction(() => !document.querySelector('[data-ps="flow-placing"]'));
    await page.waitForTimeout(500);
    const st1 = await page.evaluate(() => document.querySelector('[data-ps="flow-place-status"]').dataset.state);
    check(['inside', 'unknown'].includes(st1), `${tag}: Best fit puts the home back (status ${st1})`);
    // drag the house
    await page.locator('[data-ps="flow-house"]').first().scrollIntoViewIfNeeded().catch(() => {});
    const box = await page.locator('[data-ps="flow-house"]').first().boundingBox();
    if (box) {
      const before = await page.evaluate(() => JSON.stringify(window.__ps.store.project.levels[0].rooms[0].polygon[0]));
      await page.mouse.move(box.x + box.width / 2, box.y + box.height / 2);
      await page.mouse.down(); await page.mouse.move(box.x + box.width / 2 + 40, box.y + box.height / 2 + 10, { steps: 5 });
      await shot('3c-dragging');
      await page.mouse.up();
      const after = await page.evaluate(() => JSON.stringify(window.__ps.store.project.levels[0].rooms[0].polygon[0]));
      check(before !== after, `${tag}: dragging moves the home`);
      await page.click('[data-ps="flow-bestfit"]'); await page.waitForTimeout(800);
    }
    // resume after refresh at step 3
    await page.waitForTimeout(1500);
    await page.reload({ waitUntil: 'domcontentloaded' });
    await page.waitForSelector('[data-ps="flow-root"]:not([hidden])');
    await page.waitForTimeout(1500);
    check(await stepNo() === 3, `${tag}: a refresh resumes at step 3`);
    await page.waitForSelector('[data-ps="flow-house"]');
    await next();
    check(await stepNo() === 4, `${tag}: Next goes to step 4`);
    await page.waitForSelector('[data-ps="flow-summary"] table');
    await page.waitForTimeout(4000);
    const lines = await page.textContent('[data-ps="flow-lines"]');
    check(/indicative|check with council/i.test(lines), `${tag}: the summary says indicative, check with council`);
    check(!/[–—]/.test(await page.evaluate(() => document.querySelector('[data-ps="flow-root"]').innerText)), `${tag}: no em or en dashes on the step`);
    check(!/compliant/i.test(await page.evaluate(() => document.querySelector('[data-ps="flow-root"]').innerText)), `${tag}: the word compliant is not used`);
    await shot('4-check');
    const placedName = await page.evaluate(() => window.__ps.store.project.placedHouse?.name);
    await next();
    await page.waitForTimeout(1500);
    check(await page.evaluate(() => document.querySelector('[data-ps="flow-root"]').hidden), `${tag}: the editor opens after step 4`);
    check(await page.evaluate((n) => window.__ps.store.project.placedHouse?.name === n && window.__ps.store.project.levels.some((l) => l.rooms.length), placedName), `${tag}: the editor holds the placed house (${placedName})`);
    check(await page.evaluate(() => !document.querySelector('[data-ps="flow-back-to-placement"]').hidden), `${tag}: Back to placement is offered in the editor`);
    await shot('5-editor');
    await page.click('[data-ps="flow-back-to-placement"]');
    await page.waitForTimeout(800);
    check(await stepNo() === 3, `${tag}: Back to placement reopens step 3`);
    await shot('3d-back-to-placement');
    await page.context().close();
  }
  // Home page card: its call to action starts the flow at step 2 with the lot set.
  const page = await newPage(browser, { width: 1440, height: 900 }, log);
  page.setDefaultTimeout(T);
  await page.goto(`${ORIGIN}/`, { waitUntil: 'domcontentloaded' });
  await page.evaluate(() => document.querySelector('#as-input')?.scrollIntoView({ block: 'start' }));
  await page.fill('#as-input', '14 Sample');
  await page.waitForSelector('#as-list li'); await page.click('#as-list li');
  let fr; for (let i = 0; i < 100 && !(fr = page.frames().find((f) => /plan-studio\/app/.test(f.url()))); i++) await page.waitForTimeout(200);
  await fr.waitForFunction(() => /Lot 7/.test(document.querySelector('[data-ps="lot-head"]')?.textContent || ''));
  await page.waitForTimeout(5000);
  check(/place a home/i.test(await fr.textContent('[data-ps="lc-edit"]')), 'home: the card button invites placing a home');
  await fr.evaluate(() => document.querySelector('[data-ps="lc-edit"]')?.click());
  await page.waitForURL(/plan-studio\/app/);
  await page.waitForSelector('[data-ps="flow-root"]:not([hidden])');
  await page.waitForTimeout(2000);
  check(await page.evaluate(() => Number(document.querySelector('[data-ps="flow-root"]').dataset.step)) === 2, 'home: the card button opens the flow at step 2');
  check(await page.evaluate(() => !!window.__ps.store.project.site.lot), 'home: the lot is already set');
  await page.waitForSelector('[data-ps="flow-home"]');
  await page.waitForTimeout(800);
  await page.screenshot({ path: path.join(OUT, 'res-home-card-to-step2-1440.png'), timeout: T });
  await page.context().close();
  await browser.close(); close();
  console.log(log.length ? 'LOG:\n' + [...new Set(log)].join('\n') : 'no console errors');
  console.log(fails.length ? `FAILED ${fails.length}` : 'ALL CHECKS PASSED');
  process.exit(fails.length ? 1 : 0);
})().catch((e) => { console.error(e); process.exit(1); });
