// Builds src/premium/exporters/html-viewer.generated.js: the 3D viewer (three.js, GLTFLoader, OrbitControls) as one
// minified string that the interactive HTML export inlines. Run after changing tools/html-viewer-entry.js or upgrading three:
//   node tools/build-html-viewer.mjs
import { build } from 'esbuild';
import { writeFileSync } from 'node:fs';
import { resolve, dirname } from 'node:path';

const root = resolve(dirname(new URL(import.meta.url).pathname), '..');
const res = await build({
  entryPoints: [resolve(root, 'tools/html-viewer-entry.js')],
  bundle: true,
  format: 'iife',
  minify: true,
  target: 'es2020',
  write: false,
  legalComments: 'none',
  logLevel: 'warning',
});
let js = res.outputFiles[0].text.trim();
// The exported file must hold no web address at all. The only ones in the bundle are XML namespace names, which are
// identifiers and are never fetched; they are split so the file contains no "http://" or "https://" text.
js = js.replace(/(["'`])(https?):\/\/([^"'`]*)\1/g, (m, q, scheme, rest) => `${q}${scheme.slice(0, 2)}${q}+${q}${scheme.slice(2)}://${rest}${q}`);
// Shader source keeps reference comments that quote web pages; drop the address, keep the comment.
js = js.replace(/\/\/ *https?:\/\/\S*/g, '//');
if (/https?:\/\//.test(js)) throw new Error('The viewer bundle still contains a web address');
const out = `// GENERATED by tools/build-html-viewer.mjs from tools/html-viewer-entry.js. Do not edit by hand.\nexport const VIEWER_JS = ${JSON.stringify(js)};\n`;
writeFileSync(resolve(root, 'src/premium/exporters/html-viewer.generated.js'), out);
console.log(`Wrote html-viewer.generated.js (${(out.length / 1024).toFixed(0)} KB)`);
