// End to end run of the commercial guided flow and the automatic car park layout, with screenshots and assertions (exit 1 on a failed check).
//   node tools/comflow-shots.cjs [outDir]        Playwright: PLAYWRIGHT_PATH or a local install
const path = require('path'); const fs = require('fs');
const { chromium } = require(process.env.PLAYWRIGHT_PATH || 'playwright');
const { startServer, newPage } = require('./resiflow-harness.cjs');
const OUT = path.resolve(process.argv[2] || '/home/claude/resiflow-shots');
const fails = []; const log = [];
const check = (ok, msg) => { console.log(`${ok ? 'ok  ' : 'FAIL'} ${msg}`); if (!ok) fails.push(msg); };
(async () => {
  fs.mkdirSync(OUT, { recursive: true });
  const { ORIGIN, close } = await startServer(Number(process.env.PORT || 8822), { commercial: true });
  const browser = await chromium.launch({ args: ['--use-gl=swiftshader', '--enable-webgl', '--ignore-gpu-blocklist'] });
  const T = 120000;
  for (const [w, hgt, tag] of [[1440, 900, '1440'], [390, 844, '390']]) {
    const page = await newPage(browser, { width: w, height: hgt }, log);
    page.setDefaultTimeout(T);
    const shot = async (n) => { await page.waitForTimeout(900); await page.screenshot({ path: path.join(OUT, `com-${n}-${tag}.png`), timeout: T }); console.log('shot', n, tag); };
    const stepNo = () => page.evaluate(() => Number(document.querySelector('[data-ps="flow-root"]')?.dataset.step || 0));
    const next = async () => { await page.click('[data-ps="flow-next"]'); await page.waitForTimeout(500); };
    const idle = async () => { await page.waitForFunction(() => !document.querySelector('[data-ps="flow-placing"]')); await page.waitForTimeout(500); };
    const sw = () => page.evaluate(() => { const c = window.__ps.store.project.commercial; return c?.siteWorks ? { bays: c.siteWorks.summary.provided, required: c.siteWorks.summary.required, x: c.siteWorks.crossovers.map((k) => k.role), n: c.buildings.length } : null; });
    await page.goto(`${ORIGIN}/plan-studio/app/?mode=commercial`, { waitUntil: 'domcontentloaded' });
    await page.waitForSelector('[data-ps="flow-root"]:not([hidden])');
    check(await stepNo() === 1, `${tag}: a fresh commercial open starts at step 1`);
    check((await page.locator('[data-ps="flow-progress"] li').count()) === 5, `${tag}: five steps`);
    await shot('1a-find');
    await page.fill('[data-ps="flow-address"]', '14 Sample');
    await page.waitForSelector('[data-ps="flow-suggest"] li');
    await page.click('[data-ps="flow-suggest"] li');
    await page.waitForSelector('[data-ps="flow-lot-label"]');
    await page.waitForTimeout(2500);
    await shot('1b-lot');
    await next();
    check(await stepNo() === 2, `${tag}: Next goes to step 2`);
    await page.waitForSelector('[data-ps="flow-type"]');
    await shot('2a-what-to-build');
    await page.click('[data-ps="flow-type"][data-type="service-station"]');
    await idle();
    await page.click('[data-ps="flow-wall-tilt"]').catch(() => {});
    await page.click('[data-ps="flow-wall-metal"]').catch(() => {});
    await shot('2b-service-station');
    await next();
    check(await stepNo() === 3, `${tag}: Next goes to step 3`);
    await page.waitForSelector('[data-ps="flow-building"]');
    await idle();
    const s0 = await sw();
    check(!!s0 && s0.x.includes('in') && s0.x.includes('out'), `${tag}: the service station has separate entry and exit crossovers (${s0 && s0.x})`);
    check(!!s0 && s0.bays > 0, `${tag}: bays are laid out automatically (${s0 && s0.bays} of ${s0 && s0.required})`);
    await shot('3a-service-station-placement');
    await page.click('[data-ps="flow-add-building"]');
    await page.waitForTimeout(1200);
    const picker = await page.locator('[data-ps="add-building-pick"]').count();
    if (picker) await page.locator('[data-ps="add-building-pick"]').first().click();
    await idle();
    const s1 = await sw();
    check(!!s1 && s1.n === 2, `${tag}: Add building adds a second building (${s1 && s1.n})`);
    check(!/\b(house|home)\b/i.test(await page.evaluate(() => document.querySelector('[data-ps="flow-root"]').innerText)), `${tag}: the commercial flow never says house or home`);
    await shot('3b-added-building');
    await page.click('[data-ps="flow-duplicate"]');
    await idle();
    const s2 = await sw();
    check(!!s2 && s2.n === 3, `${tag}: Duplicate adds a copy (${s2 && s2.n})`);
    await page.click('[data-ps="flow-rerun-carpark"]');
    await idle();
    check(!!(await sw()), `${tag}: Re-run car park layout keeps a layout`);
    const b0 = await page.evaluate(() => JSON.stringify(window.__ps.store.project.commercial.buildings.map((b) => b.place)));
    await page.click('[data-ps="flow-nudge-right"]'); await page.waitForTimeout(300);
    check(b0 !== await page.evaluate(() => JSON.stringify(window.__ps.store.project.commercial.buildings.map((b) => b.place))), `${tag}: nudge moves the building`);
    await page.click('[data-ps="flow-layout-next"]'); await idle();
    await page.click('[data-ps="flow-bestfit"]'); await idle();
    await shot('3c-after-best-fit');
    await next();
    check(await stepNo() === 4, `${tag}: Next goes to step 4`);
    await page.waitForTimeout(3000);
    const txt = await page.evaluate(() => document.querySelector('[data-ps="flow-root"]').innerText);
    check(/estimates only/i.test(txt), `${tag}: the check step says estimates only`);
    check(!/[–—]/.test(txt) && !/compliant/i.test(txt), `${tag}: no dashes, never compliant`);
    await shot('4-check');
    await next();
    await page.waitForTimeout(2500);
    check(await page.evaluate(() => document.querySelector('[data-ps="flow-root"]').hidden), `${tag}: the editor opens after step 4`);
    check(await page.evaluate(() => !document.querySelector('[data-ps="flow-back-to-placement"]').hidden), `${tag}: Back to placement is offered`);
    await page.evaluate(() => window.__ps.store.setUI({ view: '2d' }));
    await shot('5-editor-2d-service-station');
    await page.evaluate(() => window.__ps.store.setUI({ view: '3d' }));
    await page.waitForTimeout(2500);
    await shot('5-editor-3d-service-station');
    await page.click('[data-ps="flow-back-to-placement"]');
    await page.waitForTimeout(800);
    check(await stepNo() === 3, `${tag}: Back to placement reopens step 3`);
    // A warehouse, through the same step 2.
    await page.click('[data-ps="flow-back"]'); await page.waitForTimeout(500);
    await page.click('[data-ps="flow-type"][data-type="warehouse"]'); await idle();
    await next(); await page.waitForSelector('[data-ps="flow-building"]'); await idle();
    const w1 = await sw();
    check(!!w1 && w1.bays > 0 && w1.x.length === 1, `${tag}: warehouse gets a car park and one crossover (${w1 && w1.bays})`);
    await shot('3d-warehouse-placement');
    await next(); await next(); await page.waitForTimeout(2000);
    await page.evaluate(() => window.__ps.store.setUI({ view: '2d' }));
    await shot('5-editor-2d-warehouse');
    // A strata unit complex.
    await page.click('[data-ps="flow-back-to-placement"]'); await page.waitForTimeout(600);
    await page.click('[data-ps="flow-back"]'); await page.waitForTimeout(500);
    await page.click('[data-ps="flow-type"][data-type="strata-units"]').catch(() => {}); await idle();
    await next(); await page.waitForTimeout(1500);
    await shot('3e-strata-placement');
    await next(); await next(); await page.waitForTimeout(2000);
    await page.evaluate(() => window.__ps.store.setUI({ view: '2d' }));
    await shot('5-editor-2d-strata');
    await page.context().close();
  }
  await browser.close(); close();
  console.log(log.length ? 'LOG:\n' + [...new Set(log)].join('\n') : 'no console errors');
  console.log(fails.length ? `FAILED ${fails.length}` : 'ALL CHECKS PASSED');
  process.exit(fails.length ? 1 : 0);
})().catch((e) => { console.error(e); process.exit(1); });
