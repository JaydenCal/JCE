// Generates src/site/fixtures/*.js: recorded-shape SAMPLE responses for the site lookup (no network).
// The lots, addresses and heights are invented. Only the response shapes follow the real services (see server/lib/site.js).
//   node tools/make-site-fixtures.mjs
import fs from 'node:fs';
import { lonLatToMga, mgaToLonLat, mgaSrid, ringArea, ringCentroid, bboxOf, round } from '../src/site/geo.js';
import { contourLines, fillGaps, gridRange } from '../src/site/contours.js';

const OUT = new URL('../src/site/fixtures/', import.meta.url);

function make(spec) {
  const { id, state, anchor, zone, headingDeg, street, lga, zoning, zoneNote, planPrefix, plan, firstLot, terrain, cell, srcRes, imagery, dem } = spec;
  const a = lonLatToMga(anchor.lon, anchor.lat, zone);
  const th = (headingDeg * Math.PI) / 180;
  const rot = ([x, y]) => [a.e + x * Math.cos(th) - y * Math.sin(th), a.n + x * Math.sin(th) + y * Math.cos(th)];
  // Local frame: x along the street, y towards the north side. Street reserve y in [-10, 10].
  const W = 20;
  const D = 40;
  const lots = [];
  let n = firstLot;
  for (let side = 0; side < 2; side++) {
    for (let k = -3; k < 3; k++) {
      const x0 = k * W;
      const y0 = side === 0 ? 10 : -10 - D;
      lots.push({ lot: n++, ring: [[x0, y0 + D], [x0 + W, y0 + D], [x0 + W, y0], [x0, y0]].map(rot), subject: side === 0 && k === 0 });
    }
  }
  // A row behind the north side, wider lots so the boundaries do not all line up.
  for (let k = -2; k < 2; k++) {
    const x0 = k * 26 + 6;
    lots.push({ lot: n++, ring: [[x0, 10 + D + 30], [x0 + 26, 10 + D + 30], [x0 + 26, 10 + D], [x0, 10 + D]].map(rot) });
  }
  const subject = lots.find((l) => l.subject);
  const c = ringCentroid(subject.ring);
  const origin = { e: round(c[0], 3), n: round(c[1], 3) };
  const rel = (ring) => ring.map(([e, nn]) => [round(e - origin.e, 3), round(nn - origin.n, 3)]);
  const poly = (l) => [{ outer: rel(l.ring), holes: [] }];
  const info = (l) => ({
    lotNumber: String(l.lot),
    planLabel: plan,
    lotLabel: `Lot ${l.lot} ${plan}`,
    areaM2: round(ringArea(l.ring), 1),
    polygons: poly(l),
  });
  const bb = bboxOf(subject.ring);
  const lotResp = {
    sample: true,
    state,
    srid: mgaSrid(zone),
    zone,
    origin,
    query: (() => { const g = mgaToLonLat(origin.e, origin.n, zone); return { lon: round(g.lon, 6), lat: round(g.lat, 6) }; })(),
    lot: { ...info(subject), section: '', lotPlan: `${subject.lot}/${plan.replace(' ', '')}`, registeredAreaM2: round(ringArea(subject.ring), 0), bboxMga: { minE: round(bb.minX, 3), minN: round(bb.minY, 3), maxE: round(bb.maxX, 3), maxN: round(bb.maxY, 3) } },
    neighbours: lots.filter((l) => !l.subject).map(info),
    lga,
    zoning,
    zoneNote,
    attribution: spec.lotAttribution,
    retrieved: '2026-11-11T00:00:00.000Z',
  };
  // Elevation grid over the lot bbox plus a 30 m buffer, rows from the north edge.
  const buf = 30;
  const minE = bb.minX - buf - origin.e;
  const maxE = bb.maxX + buf - origin.e;
  const minN = bb.minY - buf - origin.n;
  const maxN = bb.maxY + buf - origin.n;
  const cols = Math.ceil((maxE - minE) / cell) + 1;
  const rows = Math.ceil((maxN - minN) / cell) + 1;
  const values = [];
  for (let j = 0; j < rows; j++) for (let i = 0; i < cols; i++) values.push(round(terrain(minE + i * cell, maxN - j * cell), 2));
  const grid = { cols, rows, cell, x0: round(minE, 3), y0: round(maxN, 3), values };
  fillGaps(grid);
  const { min, max } = gridRange(grid);
  const contours = {
    sample: true,
    srid: mgaSrid(zone),
    origin,
    minor: 0.5,
    major: 2.5,
    minRL: min,
    maxRL: max,
    grid,
    contours: contourLines(grid, { minor: 0.5, major: 2.5 }),
    provenance: dem,
  };
  const abb = { minE: round(bb.minX - 30, 3), minN: round(bb.minY - 30, 3), maxE: round(bb.maxX + 30, 3), maxN: round(bb.maxY + 30, 3) };
  const widthPx = Math.ceil((abb.maxE - abb.minE) / srcRes);
  const heightPx = Math.ceil((abb.maxN - abb.minN) / srcRes);
  const aerial = { sample: true, synthetic: true, srid: mgaSrid(zone), georef: 'mga', bbox: abb, widthPx, heightPx, mmPerPx: round(((abb.maxE - abb.minE) / widthPx) * 1000, 3), ...imagery };
  const search = [{ label: spec.label, state, lon: lotResp.query.lon, lat: lotResp.query.lat }, ...spec.otherLabels.map((l, i) => ({ label: l, state, lon: round(lotResp.query.lon + 0.0004 * (i + 1), 6), lat: lotResp.query.lat }))];
  const js = `// SAMPLE site lookup responses (invented lots, no real parcel). Generated by tools/make-site-fixtures.mjs.\n// Shapes match GET /api/site/search, /lot, /aerial (metadata) and /contours. Used while CONFIG.siteMock is true.\nexport default ${JSON.stringify({ id, label: spec.label, search, lot: lotResp, aerial, contours }, null, 0)};\n`;
  fs.writeFileSync(new URL(`${id}.js`, OUT), js);
  console.log(id, lots.length, 'lots', cols, 'x', rows, 'grid', contours.contours.length, 'contour lines', Math.round(js.length / 1024), 'KB');
}

