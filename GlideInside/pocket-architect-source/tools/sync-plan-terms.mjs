// Rewrites the text block of website-live/plan-terms.html from src/legal/plan-terms.js (the one source of the plan set terms).
//   node tools/sync-plan-terms.mjs          write the page
//   node tools/sync-plan-terms.mjs --check  exit 1 when the page is out of date
import fs from 'node:fs';
import { PLAN_TERMS, isDraft } from '../src/legal/plan-terms.js';

const FILE = new URL('../../website-live/plan-terms.html', import.meta.url);
const BEGIN = '<!-- plan-terms:begin (generated by tools/sync-plan-terms.mjs from src/legal/plan-terms.js; edit that file, not this block) -->';
const END = '<!-- plan-terms:end -->';
const esc = (t) => String(t).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;');

export function renderBlock(t = PLAN_TERMS) {
  return [
    BEGIN,
    '<section class="shell hero-centre" style="padding-bottom:12px">',
    `  <p class="eyebrow">Plan set terms</p>`,
    `  <h1 style="font-size:clamp(36px,5vw,60px)">${esc(t.title)}</h1>`,
    '</section>',
    '<section class="shell legal" data-plan-terms>',
    `<p class="updated">Version <span data-plan-terms-version>${esc(t.version)}</span>, effective ${esc(t.effectiveDate)}</p>`,
    isDraft(t) ? '<p class="updated" role="note"><strong>Draft wording, pending legal review.</strong></p>' : '',
    `<div class="plan-terms-body">${t.bodyHtml}</div>`,
    '<p>These terms apply to every plan set PDF and DXF file made with Glide Inside. They are shown and accepted before a file is generated. The same version is printed on the plan set.</p>',
    '<p><a class="link" href="terms.html">Order terms</a> &nbsp; <a class="link" href="privacy.html">Privacy policy</a></p>',
    '</section>',
    END,
  ].filter(Boolean).join('\n');
}

export function syncPage(html, t = PLAN_TERMS) {
  const a = html.indexOf(BEGIN);
  const b = html.indexOf(END);
  if (a < 0 || b < a) throw new Error('plan-terms.html has no plan-terms:begin / plan-terms:end markers');
  return html.slice(0, a) + renderBlock(t) + html.slice(b + END.length);
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const cur = fs.readFileSync(FILE, 'utf8');
  const next = syncPage(cur);
  if (process.argv.includes('--check')) { if (cur !== next) { console.error('website-live/plan-terms.html is out of date: run node tools/sync-plan-terms.mjs'); process.exit(1); } } else { fs.writeFileSync(FILE, next); console.log('plan-terms.html written for version', PLAN_TERMS.version); }
}
