// Writes src/portal/glide-library.generated.js: card data (name, beds, baths, garage, area, size, storeys, thumbnail) for every
// Glide Inside template, so the builder dashboard can list the library without loading the 3D catalogue.
// Run after adding a template to src/catalogue/templates.js:  node tools/build-glide-library.mjs
import { writeFileSync } from 'node:fs';
import { resolve, dirname } from 'node:path';
import { TEMPLATES, createFromTemplate } from '../src/catalogue/templates.js';
import { houseStats } from '../src/portal/house-stats.js';
import { projectToSvg } from '../src/portal/thumbnail.js';

const root = resolve(dirname(new URL(import.meta.url).pathname), '..');
const CATEGORY = { house: 'House', unit: 'Granny flat, unit or duplex', shed: 'Shed', extension: 'Extension' };
const items = TEMPLATES.filter((t) => t.id !== 'blank').map((t) => {
  const project = createFromTemplate(t.id);
  return {
    id: `glide:${t.id}`,
    templateId: t.id,
    name: t.name,
    description: t.description,
    type: t.type,
    category: CATEGORY[t.type] || 'Design',
    ...houseStats(project),
    thumbnail: projectToSvg(project),
  };
});
const out = `// GENERATED by tools/build-glide-library.mjs. Do not edit by hand.\nexport const GLIDE_LIBRARY = ${JSON.stringify(items, null, 2)};\n`;
writeFileSync(resolve(root, 'src/portal/glide-library.generated.js'), out);
console.log(`Wrote ${items.length} Glide Inside models.`);
